const distMax = 0.32;

// Капс-выкрики (ВЫГЛЯДИТ, ОРИГИНАЛ, НЕНАДЁЖНА, ЧИСТОМ…) в данных читаются как крик — гасим их одной
// регуляркой (слово из 5+ заглавных кириллических букв → строчные), не привязываясь к точным литералам:
// если формулировку в данных поправят на символ, нормализация всё равно сработает. Аббревиатуры короче
// (ГАРФ, PD, К.Р.) под правило не попадают.
const deCaps = (s) => s.replace(/[А-ЯЁ]{5,}/g, (m) => m.toLowerCase());

// В читаемом тексте марку и версию модели заменяем на бытовое «автоматическая модель»: для широкой
// аудитории важно, что разбор машинный, а не какой сервис. Скобку ловим по упоминанию модели, а не по
// всей длинной строке — так замена переживёт правку формулировки в данных.
const plainModel = (s) =>
  deCaps(
    s
      .replace(/\((?=[^)]*(?:Gemini|VertexAI))[^)]*\)/g, "(автоматической моделью, которая разбирает изображения)")
      .replace("на развороте ПОХОЖЕ одна рука", "на развороте, похоже, одна рука") // добавляем запятые
      .replace("Это эвристика по одной странице", "Это грубая оценка по одной странице") // жаргон → быт
  );

// Честная сноска про источник писем: жаргон «size-matched, бутстрап» → уже введённое бытовое описание
// уравнивания; капс-выкрики (ОРИГИНАЛ, НЕНАДЁЖНА, ЧИСТОМ) гасит deCaps.
const plainNote = (s) =>
  deCaps(s.replace("при уравнивании объёмов (size-matched, бутстрап)", "при равном объёме, в повторных выборках")
    .replace("Честные ограничения данных по письмам Николая.", "Состав писем Николая.")
    .replace("— опускаем.", "здесь не оценена."));

// Примечание под панелью регистра приходит из данных с жаргоном (перестановочный тест, силуэт, логбук,
// «регистр», n) — отзеркаливаем уже введённые в тексте бытовые слова.
const plainPanelNote = (s) =>
  deCaps(
    s
      .replace("перестановочный тест", "проверка на случайность")
      .replace("при силуэте", "при чёткости деления надвое")
      .replace("Сухой логбук", "Сухой служебный журнал")
      .replace("чьи дневники нарративны,", "чьи дневники похожи на живой рассказ,")
      .replace("это пол перестановочного теста для двух точек", "это нижняя возможная граница для двух точек")
      .replace("регистр как общий класс на таком n не установить", "такой стиль как общий класс на двух дневниках не установить")
      .replace("«регистр правящего монарха»", "«стиль правящего монарха»")
  );

function DistRow({ name, v, hi }) {
  return (
    <EditorialBar
      value={v}
      max={distMax}
      accent={hi ? "var(--cinnabar)" : "var(--text-muted)"}
      valueText={fmtScore(v, 3)}
      label={<span style={{ color: hi ? "var(--text)" : "var(--text-muted)", fontWeight: hi ? 700 : 400 }}>{name}</span>}
    />
  );
}

// строка панели регистра: позиция дневника на оси «монарх (0) ↔ писатель (1)» по служебным словам
function AxisRow({ r }) {
  const accent = r.isThrone ? "var(--cinnabar)" : r.group === "великий князь" ? "var(--icon-blue)" : "var(--text-muted)";
  const tag = r.period ? `  · ${r.period}` : "";
  return (
    <EditorialBar
      value={r.axis}
      max={1}
      accent={accent}
      valueText={r.closer}
      label={<span style={{ color: r.isRoyal ? "var(--text)" : "var(--text-muted)", fontWeight: r.isThrone ? 700 : 400 }}>
        {r.name}<span className="muted" style={{ fontWeight: 400 }}>{tag}</span>
      </span>}
    />
  );
}

